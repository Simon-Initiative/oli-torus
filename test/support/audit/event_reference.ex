defmodule Oli.Auditing.EventReference do
  @moduledoc """
  Renders `docs/design-docs/audit-log-events.md` from `Oli.Auditing.EventCatalog` and
  `Oli.Auditing.EventExamples`.

  Regenerate with `MIX_ENV=test mix run test/support/audit_log_event_reference.exs`.
  `test/oli/auditing/event_reference_test.exs` fails when the committed file is stale.
  """

  alias Oli.Auditing.{Context, EventCatalog, EventExamples}
  alias Oli.Auditing.EventCatalog.{Contract, Validation}

  @path "docs/design-docs/audit-log-events.md"

  @columns [
    {:id, "Row identifier from `audit_events_id_seq`. Unique together with `inserted_at`."},
    {:inserted_at,
     "When the row was recorded (UTC). Partition key; date filters and sorting use it."},
    {:occurred_at,
     "When the action happened. Differs from `inserted_at` only for late-recorded async outcomes. `NULL` on migrated rows."},
    {:schema_version,
     "`2` for events written by the application; `1` for migrated history whose unknown fields stay `NULL`."},
    {:event_type, "What happened. One of the catalog names below."},
    {:outcome, "Result: #{Enum.map_join(Validation.outcomes(), ", ", &"`#{&1}`")}."},
    {:actor_type,
     "Who acted: `user`, `author`, `system`; `unknown` only on migrated rows without an actor."},
    {:actor_key,
     "System actor key when `actor_type` is `system`: #{Enum.map_join(Context.system_keys(), ", ", &"`#{&1}`")}."},
    {:user_id, "Acting user, when the actor is a user."},
    {:author_id, "Acting author, when the actor is an author."},
    {:actor_snapshot,
     "Actor identity at the time: `id`, `name`, `email` for accounts; `key`, `label` for system actors."},
    {:entity_type, "Kind of record the event is about, from the event contract."},
    {:entity_id,
     "Identifier of that record as text: numeric ID, UUID, stable key, or composite such as `section:301/resource:4512/user:77`."},
    {:entity_snapshot,
     "Identity of the record at the time (allowlisted fields only), readable after it is renamed or deleted."},
    {:affected_user_id,
     "Learner or user the action was done to, when different from the actor's role in the event."},
    {:affected_author_id, "Author the action was done to."},
    {:project_id, "Project the event belongs to, whenever known."},
    {:section_id, "Section, product, or blueprint the event belongs to, whenever known."},
    {:resource_id,
     "Resource (page, assessment, container, objective) the event belongs to, whenever known."},
    {:institution_id, "Institution the event belongs to, whenever known."},
    {:refs,
     "Other related records as `{role, type, id, label}`; roles: #{Enum.map_join(Validation.ref_roles(), ", ", &"`#{&1}`")}."},
    {:changes,
     "Per-field records `{operation, before, after, ...}` limited to the contract's fields; secret fields only record `redacted: true`; at most #{Validation.max_changes_bytes()} bytes."},
    {:details,
     "Extra facts limited to the contract's keys; at most #{Validation.max_details_bytes()} bytes."},
    {:source,
     "Where the change originated: #{Enum.map_join(Context.sources(), ", ", &"`#{&1}`")}."},
    {:operation_id, "Command that produced the event; events of one bulk command share it."},
    {:parent_operation_id,
     "Operation that spawned this one, such as the publish that started a publication-application job."},
    {:event_key,
     "Deterministic slot of the event inside its operation, such as `exception:77:updated`."},
    {:legacy_source,
     "Migrated rows only: source table (`audit_log_events` or `settings_changes`)."},
    {:legacy_id, "Migrated rows only: the row's ID in its source table."},
    {:search_text, "Text indexed for search, built from snapshots and reference labels."},
    {:search_vector, "Generated `tsvector` of `search_text` (`simple` configuration)."}
  ]

  @doc "Returns the repository-relative path of the generated reference."
  @spec path() :: String.t()
  def path, do: @path

  @doc "Renders the reference markdown."
  @spec render() :: String.t()
  def render do
    [
      header(),
      columns_section(),
      families_section(),
      Enum.map(EventCatalog.families(), &family_section/1)
    ]
    |> List.flatten()
    |> Enum.join("\n")
  end

  defp header do
    [
      "# Audit Log Events",
      "",
      "<!-- Generated by Oli.Auditing.EventReference. Do not edit by hand. -->",
      "<!-- Regenerate: MIX_ENV=test mix run test/support/audit_log_event_reference.exs -->",
      "",
      "Reference for every event stored in `audit_log_events`. Families, labels, and descriptions",
      "live in `Oli.Auditing.EventCatalog` (code), not in the database. Each example shows the",
      "columns an event sets; omitted columns are `NULL`, `{}`, or `[]`.",
      ""
    ]
  end

  defp columns_section do
    [
      "## Columns",
      "",
      "| Column | Meaning |",
      "| --- | --- |",
      Enum.map(@columns, fn {column, meaning} -> "| `#{column}` | #{meaning} |" end),
      ""
    ]
  end

  defp families_section do
    [
      "## Families",
      "",
      "| Family | Events |",
      "| --- | --- |",
      Enum.map(EventCatalog.families(), fn family ->
        events = family |> EventCatalog.family_events() |> Enum.map_join(", ", &"`#{&1}`")
        "| #{EventCatalog.family_label(family)} | #{events} |"
      end),
      ""
    ]
  end

  defp family_section(family) do
    [
      "## #{EventCatalog.family_label(family)}",
      "",
      family |> EventCatalog.family_events() |> Enum.map(&event_section/1)
    ]
  end

  defp event_section(name) do
    contract = EventCatalog.contract!(name)

    [
      "### `#{name}`",
      "",
      "**#{contract.label}.** #{contract.description}",
      "",
      "| Rule | Value |",
      "| --- | --- |",
      rules(contract),
      "",
      "Example:",
      "",
      "```json",
      example_json(name),
      "```",
      ""
    ]
  end

  defp rules(%Contract{} = contract) do
    [
      {"Actors", list(contract.actor_kinds)},
      {"Entity types", list(contract.entity_types)},
      {"Required columns", list(contract.required)},
      {"At least one of", list(contract.required_one_of)},
      {"Affected person", affected(contract)},
      {"Outcomes", list(contract.outcomes)},
      {"No-op policy", no_op(contract.no_op)},
      {"Change fields", change_fields(contract.change_fields)},
      {"Detail keys", list(contract.detail_keys)},
      {"Reference roles", list(contract.ref_roles)},
      {"Status", status(contract)}
    ]
    |> Enum.map(fn {rule, value} -> "| #{rule} | #{value} |" end)
  end

  defp affected(%Contract{affected_kinds: []}), do: "none"

  defp affected(contract) do
    requirement = requirement(contract.affected_required)
    subject = subject_note(contract.subject_is_affected)
    "#{list(contract.affected_kinds)} (#{requirement}#{subject})"
  end

  defp requirement(true), do: "required"
  defp requirement(false), do: "optional"

  defp subject_note(true), do: "; equals the entity"
  defp subject_note(false), do: ""

  defp no_op(:skip), do: "`skip` (an event with no changes is not written)"
  defp no_op(:lifecycle), do: "`lifecycle` (written without changes)"

  defp change_fields(fields) when map_size(fields) == 0, do: "none"

  defp change_fields(fields) do
    fields
    |> Enum.sort()
    |> Enum.map_join(", ", fn
      {field, :secret} -> "`#{field}` (secret)"
      {field, :value} -> "`#{field}`"
    end)
  end

  defp status(%Contract{v1_only: true}), do: "migrated history only"
  defp status(%Contract{deprecated: true}), do: "deprecated"
  defp status(_contract), do: "active"

  defp list([]), do: "none"
  defp list(values), do: Enum.map_join(values, ", ", &"`#{&1}`")

  defp example_json(name) do
    example = EventExamples.example(name)

    @columns
    |> Enum.map(fn {column, _meaning} -> {column, Map.get(example, column)} end)
    |> Enum.reject(fn {_column, value} -> value in [nil, %{}, [], ""] end)
    |> Enum.map(fn {column, value} ->
      "  #{Jason.encode!(to_string(column))}: #{encode(value)}"
    end)
    |> Enum.join(",\n")
    |> then(&"{\n#{&1}\n}")
  end

  defp encode(%DateTime{} = value), do: Jason.encode!(DateTime.to_iso8601(value))
  defp encode(value), do: Jason.encode!(value)
end
