defmodule Oli.Schemas.ContentDispatcher do
  @moduledoc """
  Build-time generation of the balanced rich-content type dispatcher.

  Concrete element definitions declare `x-torus-dispatch` as true for standalone
  elements or false for structured sub-elements. Types come from their `type`
  constants; aggregate context enums remain explicit authoring policy. Duplicate
  types need conditional variants (`x-torus-dispatch-when`) and one fallback.
  This module is never called during content validation.
  """

  @doc "Regenerates the typed-element definition from annotated concrete elements."
  @spec generate(map()) :: map()
  def generate(%{"$defs" => definitions} = schema) do
    variants =
      definitions
      |> Enum.sort_by(&elem(&1, 0))
      |> Enum.flat_map(fn {name, definition} ->
        case element_types(definition) do
          [] ->
            case Map.has_key?(definition, "x-torus-dispatch") do
              true ->
                raise ArgumentError,
                      "$defs/#{name} must define string type constants to declare dispatch"

              false ->
                []
            end

          types ->
            dispatch_entries(name, definition, types)
        end
      end)
      |> Enum.group_by(fn {type, _, _} -> type end)

    case map_size(variants) do
      0 -> raise ArgumentError, "No standalone content elements declared"
      _ -> :ok
    end

    check_contexts!(definitions, Map.keys(variants))

    branches =
      variants
      |> Enum.sort_by(&elem(&1, 0))
      |> Enum.map(fn {type, entries} -> {type, variant_schema!(type, entries)} end)

    dispatcher = %{
      "type" => "object",
      "required" => ["type"],
      "properties" => %{"type" => %{"enum" => Enum.map(branches, &elem(&1, 0))}},
      "allOf" => [balanced_tree(branches)],
      "$comment" =>
        "Generated by mix oli.generate_content_dispatcher. Edit annotated element definitions, not this dispatch table.",
      "description" =>
        "Balanced type dispatch selects the element schema before validating descendants."
    }

    put_in(schema, ["$defs", "typed-element"], dispatcher)
  end

  defp element_types(%{"properties" => %{"type" => %{"const" => type}}}) when is_binary(type),
    do: [type]

  defp element_types(%{"properties" => %{"type" => %{"oneOf" => types}}}) do
    Enum.map(types, fn
      %{"const" => type} when is_binary(type) -> type
      _ -> raise ArgumentError, "Content type alternatives must be string constants"
    end)
  end

  defp element_types(_), do: []

  defp dispatch_entries(name, definition, types) do
    case Map.fetch(definition, "x-torus-dispatch") do
      {:ok, true} -> Enum.map(types, &{&1, name, definition["x-torus-dispatch-when"]})
      {:ok, false} -> []
      _ -> raise ArgumentError, "$defs/#{name} must declare x-torus-dispatch as true or false"
    end
  end

  defp variant_schema!(type, entries) do
    {fallback, conditional} =
      Enum.split_with(entries, fn {_, _, condition} -> is_nil(condition) end)

    case fallback do
      [{_, name, nil}] ->
        Enum.reduce(Enum.reverse(conditional), reference(name), fn
          {_, name, condition}, otherwise when is_map(condition) ->
            %{"if" => condition, "then" => reference(name), "else" => otherwise}

          _entry, _otherwise ->
            raise ArgumentError, "Invalid dispatch condition for #{type}"
        end)

      _ ->
        raise ArgumentError, "Content type #{type} needs exactly one unconditional fallback"
    end
  end

  defp balanced_tree([{_type, schema}]), do: schema

  defp balanced_tree(branches) do
    {left, right} = Enum.split(branches, div(length(branches), 2))

    %{
      "if" => %{"properties" => %{"type" => %{"enum" => Enum.map(left, &elem(&1, 0))}}},
      "then" => balanced_tree(left),
      "else" => balanced_tree(right)
    }
  end

  # Context enums constrain placement; they may only name dispatchable elements.
  defp check_contexts!(definitions, types) do
    for {name, definition} <- definitions, name != "typed-element" do
      context = Map.get(definition, "then", definition)

      case context do
        %{"properties" => %{"type" => %{"enum" => members}}} ->
          case members -- types do
            [] ->
              :ok

            unknown ->
              raise ArgumentError,
                    "$defs/#{name} names unknown element types: #{inspect(unknown)}"
          end

        _ ->
          :ok
      end
    end
  end

  defp reference(name) do
    token = name |> String.replace("~", "~0") |> String.replace("/", "~1")
    %{"$ref" => "#/$defs/#{token}"}
  end
end
